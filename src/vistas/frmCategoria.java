    private void tblCategoriaMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCategoriaMousePressed
        
        JTable tabla = (JTable) evt.getSource();
        Point punto = evt.getPoint();
        int row = tabla.rowAtPoint(punto);
        if (evt.getClickCount() == 1) {
            idCategoriaX = Integer.parseInt(tabla.getValueAt(tabla.getSelectedRow(), 0).toString());
            txtNombre.setText(tabla.getValueAt(tabla.getSelectedRow(), 1).toString());
        }
    }//GEN-LAST:event_tblCategoriaMousePressed

    
    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        
        int fila_seleccionada = tblCategoria.getSelectedRow();
        if (fila_seleccionada >= 0) {
            int decision = JOptionPane.showConfirmDialog(null, "¿Está seguro/a que desea eliminar esta categoria?", "Advertencia", JOptionPane.YES_NO_OPTION);
            if (decision == 0) {
                try {
                    this.tarea_categoria.eliminar(Conexion.obtener(), this.categoria.get(fila_seleccionada));
                    this.cargar_lista_categorias();
                } catch (SQLException ex) {
                    System.out.println(ex.getMessage());
                    JOptionPane.showMessageDialog(this, "Ha surgido un error y no se ha podido eliminar el registro.");
                } catch (ClassNotFoundException ex) {
                    System.out.println(ex);
                    JOptionPane.showMessageDialog(this, "Ha surgido un error y no se ha podido eliminar el registro.(clase no encontrada)");
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Por favor seleccione una fila.");
        }
        
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        this.nombre = txtBuscarCategoria.getText();
        this.cargar_lista_categoria_nombre();
        if ("".equals(nombre)){
            JOptionPane.showMessageDialog(this, "Debes escribir lo que necesitas buscar");
        }
        if(tarea_categoria.isF()==true){
            JOptionPane.showMessageDialog(this, "Categoria encontrada");
        } else {
            JOptionPane.showMessageDialog(this, "Categoria no encontrada");
            this.cargar_lista_categorias();
        }

        this.nombre ="";
    }//GEN-LAST:event_btnBuscarActionPerformed


