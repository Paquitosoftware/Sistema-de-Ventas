    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        
        
        int fila_seleccionada = tblCategoria.getSelectedRow();
        if (fila_seleccionada >= 0){
            txtNombre.setEnabled(true);
            
            this.tablaCategoria = new Categoria();
            String nombre = txtNombre.getText();
            
            this.tablaCategoria.setId_categoria(idCategoriaX);
            this.tablaCategoria.setNombre(nombre);
            
            try {
                this.tarea_categoria.editar(Conexion.obtener(), this.tablaCategoria);
                this.cargar_lista_categorias();

            } catch (SQLException ex) {
                System.out.println(ex.getMessage());
                JOptionPane.showMessageDialog(this, "Ha surgido un error y no se ha podido guardar el registro.");
            } catch (ClassNotFoundException ex) {
                System.out.println(ex);
                JOptionPane.showMessageDialog(this, "Ha surgido un error y no se ha podido guardar el registro.");
            }
            btnGuardar.setEnabled(false);
            txtNombre.setText("");
            txtNombre.setEnabled(false);
        } else {
            JOptionPane.showMessageDialog(this, "Por favor seleccione una fila.");
        }
        
    }//GEN-LAST:event_btnGuardarActionPerformed

