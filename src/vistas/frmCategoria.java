    private void cargar_lista_categorias(){
        try{
            this.categoria = this.tarea_categoria.recuperarTodas(Conexion.obtener());
            DefaultTableModel dtm = (DefaultTableModel) tblCategoria.getModel();
            dtm.setRowCount(0);
            for(int i =0; i<this.categoria.size();i++){
                dtm.addRow(new Object[]{
                    this.categoria.get(i).getId_categoria(),
                    this.categoria.get(i).getNombre(),
                });   
            }
        }catch(SQLException ex){
           System.out.println(ex.getMessage());
           JOptionPane.showMessageDialog(this, "Ha surgido un error de SQL y no se ha podido recuperar los reguistros ");
        }catch(ClassNotFoundException ex){
            System.out.println(ex.getMessage());
           JOptionPane.showMessageDialog(this, "Ha surguido un error no se encuentra la clase");        
        }   
    }
    
