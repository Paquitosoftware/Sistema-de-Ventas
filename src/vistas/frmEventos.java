    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        
        int fila_seleccionada = tblEvento.getSelectedRow();
        String nombreE = txtEvento.getText();
        if (fila_seleccionada >= 0){
            
            if(jdcFecha.getDate()==null||"".equals(nombreE)){
            JOptionPane.showMessageDialog(this, "Por favor llene correctamente los campos para ingresar informaciòn.");
            } else {
                this.tablaEvento = new Evento();

                DateFormat dateFormat = new SimpleDateFormat("yyyy-MM-d");  
                String fechaSelect = dateFormat.format(jdcFecha.getDate());
                
                this.tablaEvento.setId_evento(idEventoX);
                tablaEvento.setNombre(nombreE);
                tablaEvento.setFecha(fechaSelect);
                
                try {
                this.tarea_evento.editar(Conexion.obtener(), this.tablaEvento);
                this.cargar_lista_eventos();

            } catch (SQLException ex) {
                System.out.println(ex.getMessage());
                JOptionPane.showMessageDialog(this, "Ha surgido un error y no se ha podido guardar el registro. Error de Mysql.");
            } catch (ClassNotFoundException ex) {
                System.out.println(ex);
                JOptionPane.showMessageDialog(this, "Ha surgido un error y no se ha podido guardar el registro. No se encuentra la clase.");
            }
            txtEvento.setEnabled(false);
            jdcFecha.setEnabled(false);
            btnAgregar.setEnabled(false);    
                
            }
        } else {
            JOptionPane.showMessageDialog(this, "Por favor seleccione una fila.");
        }
        
    }//GEN-LAST:event_btnGuardarActionPerformed

