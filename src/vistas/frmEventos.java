    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        //jdcFecha.setDateFormatString("yyyy/MM/d");
        String nombreE = txtEvento.getText();
        
        //System.out.print();
        
        if(jdcFecha.getDate()==null||"".equals(nombreE)){
            JOptionPane.showMessageDialog(this, "Por favor llene correctamente los campos para ingresar informaciòn.");
        } else {
        
            this.tablaEvento = new Evento();
            
            DateFormat dateFormat = new SimpleDateFormat("yyyy-MM-d");  
            String fechaSelect = dateFormat.format(jdcFecha.getDate());
            
            tablaEvento.setNombre(nombreE);
            tablaEvento.setFecha(fechaSelect);
            
            try {
            this.tarea_evento.guardar(Conexion.obtener(), this.tablaEvento, txtMonto.getText());
            this.cargar_lista_eventos();
            
        } catch (SQLException ex) {
            System.out.println(ex.getMessage());
            JOptionPane.showMessageDialog(this, "Ha surgido un error y no se ha podido guardar el registro.");
        } catch (ClassNotFoundException ex) {
            System.out.println(ex);
            JOptionPane.showMessageDialog(this, "Ha surgido un error y no se ha podido guardar el registro.");
        }
        txtEvento.setEnabled(false);
        jdcFecha.setEnabled(false);
        btnAgregar.setEnabled(false);  
        txtMonto.setEnabled(false);
    }
    }//GEN-LAST:event_btnAgregarActionPerformed

